import { test, describe, before, after } from 'node:test';
import assert from 'node:assert/strict';
import request from 'supertest';
import { createApp } from '../src/app.js';
import { connectDB, disconnectDB } from '../src/config/db.js';
import User from '../src/models/User.js';
import Incident from '../src/models/Incident.js';
import AuditLog from '../src/models/AuditLog.js';
import Resolution from '../src/models/Resolution.js';

describe('ResolveIQ Phase 4: Complete Incident Management Workflow', () => {
  let app;
  let commanderUser, engineerUser, clientUser;
  let commanderCookie, engineerCookie, clientCookie;
  let createdIncident;
  let secondaryIncident;

  before(async () => {
    process.env.NODE_ENV = 'test';
    process.env.JWT_SECRET = 'phase4_incident_management_jwt_secret_test';
    await connectDB();
    app = createApp();

    // Provision test users
    commanderUser = await User.create({
      name: 'Incident Commander Dana',
      email: `commander_${Date.now()}@resolveiq.io`,
      password: 'EnterprisePass123!',
      role: 'manager',
      team: 'Platform Ops',
      isActive: true,
    });

    engineerUser = await User.create({
      name: 'Senior SRE Marcus',
      email: `sre_${Date.now()}@resolveiq.io`,
      password: 'EnterprisePass123!',
      role: 'support_engineer',
      team: 'Platform SRE',
      isActive: true,
    });

    clientUser = await User.create({
      name: 'Client Reporter Elena',
      email: `elena_${Date.now()}@customer.io`,
      password: 'EnterprisePass123!',
      role: 'end_user',
      team: 'Customer Care',
      isActive: true,
    });

    // Obtain HttpOnly session cookies
    const loginAndGetCookie = async (user) => {
      const res = await request(app).post('/api/v1/auth/login').send({
        email: user.email,
        password: 'EnterprisePass123!',
      });
      assert.equal(res.status, 200);
      const cookies = res.headers['set-cookie'];
      return Array.isArray(cookies) ? cookies[0] : cookies || '';
    };

    commanderCookie = await loginAndGetCookie(commanderUser);
    engineerCookie = await loginAndGetCookie(engineerUser);
    clientCookie = await loginAndGetCookie(clientUser);
  });

  after(async () => {
    await disconnectDB();
  });

  test('1. Authenticate & Create Incident with deterministic priority matrix and reproduction steps', async () => {
    const res = await request(app)
      .post('/api/v1/incidents')
      .set('Cookie', clientCookie)
      .send({
        title: 'Elevated 504 Gateway Timeouts on Edge Ingress Proxy',
        description: 'Customer traffic dropping intermittently with Envoy upstream timeout spikes.',
        affectedService: 'ingress-envoy-gateway',
        impact: 'enterprise', // enterprise + critical -> P1
        urgency: 'critical',
        source: 'prometheus',
        category: 'availability',
        reproductionSteps: '1. Curl https://api.resolveiq.io/v1/health\n2. Observe random 504 status after 30s connection stall',
        assignedTeam: 'Platform SRE',
        environment: 'production',
        tags: ['envoy', 'edge', 'p1-outage'],
      });

    assert.equal(res.status, 201);
    assert.equal(res.body.success, true);
    assert.ok(res.body.incident);

    createdIncident = res.body.incident;

    // Verify sequential ticket number generated by server
    assert.match(createdIncident.incidentNumber, /^INC-\d+/);
    // Verify deterministic ITIL matrix priority derived: enterprise + critical -> P1
    assert.equal(createdIncident.priority, 'P1');
    assert.equal(createdIncident.status, 'triggered');
    assert.equal(createdIncident.affectedService, 'ingress-envoy-gateway');
    assert.match(createdIncident.reproductionSteps, /504 status/);
    assert.equal(createdIncident.reporter.toString(), clientUser._id.toString());
    assert.ok(createdIncident.sla?.responseDeadline);
    assert.ok(createdIncident.sla?.resolutionDeadline);
  });

  test('2. View Incident detail and verify populated reporter, SLA targets, and initial audit record', async () => {
    const res = await request(app)
      .get(`/api/v1/incidents/${createdIncident.incidentNumber}`)
      .set('Cookie', engineerCookie);

    assert.equal(res.status, 200);
    assert.equal(res.body.success, true);
    assert.equal(res.body.incident.incidentNumber, createdIncident.incidentNumber);
    assert.equal(res.body.incident.reporter.name, clientUser.name);
    assert.ok(Array.isArray(res.body.incident.auditLogs));
    assert.ok(res.body.incident.auditLogs.length >= 1);
    assert.equal(res.body.incident.auditLogs[0].action, 'INCIDENT_CREATED');
  });

  test('3. Query, search, filter and paginate incidents', async () => {
    // Create a secondary incident to test search and filtering
    const resSec = await request(app)
      .post('/api/v1/incidents')
      .set('Cookie', commanderCookie)
      .send({
        title: 'Database Read Replica Lag Exceeding 120s Threshold',
        description: 'Postgres streaming replication latency alarming on reporting queries.',
        affectedService: 'postgresql-replica-02',
        impact: 'department',
        urgency: 'moderate', // department + moderate -> P3
        source: 'datadog',
        assignedTeam: 'Platform SRE',
      });
    assert.equal(resSec.status, 201);
    secondaryIncident = resSec.body.incident;

    // Search by title keyword
    const resSearch = await request(app)
      .get('/api/v1/incidents?search=Postgres')
      .set('Cookie', engineerCookie);
    assert.equal(resSearch.status, 200);
    assert.ok(resSearch.body.incidents.some((i) => i.incidentNumber === secondaryIncident.incidentNumber));
    assert.equal(resSearch.body.incidents.some((i) => i.incidentNumber === createdIncident.incidentNumber), false);

    // Filter by priority
    const resPriorityFilter = await request(app)
      .get('/api/v1/incidents?priority=P1')
      .set('Cookie', engineerCookie);
    assert.equal(resPriorityFilter.status, 200);
    assert.ok(resPriorityFilter.body.incidents.every((i) => i.priority === 'P1'));

    // Pagination verification
    const resPage = await request(app)
      .get('/api/v1/incidents?page=1&limit=1')
      .set('Cookie', commanderCookie);
    assert.equal(resPage.status, 200);
    assert.equal(resPage.body.incidents.length, 1);
    assert.equal(resPage.body.page, 1);
    assert.ok(resPage.body.totalPages >= 2);
    assert.ok(resPage.body.total >= 2);
  });

  test('4. Edit non-restricted incident fields and verify restricted fields cannot be tampered with', async () => {
    const resEdit = await request(app)
      .put(`/api/v1/incidents/${createdIncident._id}`)
      .set('Cookie', engineerCookie)
      .send({
        title: 'Elevated 504 Gateway Timeouts on Edge Ingress Proxy (Mitigation in Progress)',
        description: 'Updated description: Envoy thread contention detected on thread pool worker 4.',
        reproductionSteps: 'Curl reproduce confirmed on EU-West cluster pods.',
        priority: 'P5', // Attempt to tamper with restricted priority
        status: 'closed', // Attempt to bypass status machine
      });

    assert.equal(resEdit.status, 200);
    assert.equal(resEdit.body.incident.title, 'Elevated 504 Gateway Timeouts on Edge Ingress Proxy (Mitigation in Progress)');
    assert.equal(resEdit.body.incident.reproductionSteps, 'Curl reproduce confirmed on EU-West cluster pods.');
    // Restricted fields remained protected!
    assert.equal(resEdit.body.incident.priority, 'P1');
    assert.equal(resEdit.body.incident.status, 'triggered');
  });

  test('5. Assign team and engineer', async () => {
    const resAssign = await request(app)
      .patch(`/api/v1/incidents/${createdIncident._id}/reassign`)
      .set('Cookie', commanderCookie)
      .send({
        assignedTeam: 'Platform SRE',
        assigneeId: engineerUser._id.toString(),
        reason: 'Assigned Marcus as Lead Responder for P1 Envoy triage',
      });

    assert.equal(resAssign.status, 200);
    assert.equal(resAssign.body.incident.assignee.toString(), engineerUser._id.toString());
    assert.equal(resAssign.body.incident.assignedTeam, 'Platform SRE');
  });

  test('6. Append investigation notes', async () => {
    const resNote = await request(app)
      .post(`/api/v1/incidents/${createdIncident._id}/notes`)
      .set('Cookie', engineerCookie)
      .send({
        note: 'Inspected thread dumps: envoy worker 4 blocked waiting for upstream connection pool mutex. Preparing hotfix config restart.',
      });

    assert.equal(resNote.status, 201);
    assert.equal(resNote.body.success, true);
    assert.equal(resNote.body.note.authorName, engineerUser.name);
    assert.ok(resNote.body.investigationNotes.length >= 1);
  });

  test('7. Link related tickets', async () => {
    const resLink = await request(app)
      .post(`/api/v1/incidents/${createdIncident._id}/related`)
      .set('Cookie', engineerCookie)
      .send({
        relatedTicketId: secondaryIncident.incidentNumber,
      });

    assert.equal(resLink.status, 200);
    assert.ok(resLink.body.relatedIncidents.some((r) => r.incidentNumber === secondaryIncident.incidentNumber));
  });

  test('8. State machine validation: Permitted transitions vs invalid transitions', async () => {
    // Invalid transition: triggered directly to resolved -> 400 Bad Request
    const resInvalid = await request(app)
      .patch(`/api/v1/incidents/${createdIncident._id}/status`)
      .set('Cookie', engineerCookie)
      .send({
        status: 'resolved',
      });
    assert.equal(resInvalid.status, 400);
    assert.match(resInvalid.body.error, /Invalid status transition/);

    // Valid transition 1: triggered -> acknowledged
    const resAck = await request(app)
      .patch(`/api/v1/incidents/${createdIncident._id}/status`)
      .set('Cookie', engineerCookie)
      .send({
        status: 'acknowledged',
        reason: 'On-call SRE paged and acknowledging alert',
      });
    assert.equal(resAck.status, 200);
    assert.equal(resAck.body.incident.status, 'acknowledged');

    // Valid transition 2: acknowledged -> investigating
    const resInv = await request(app)
      .patch(`/api/v1/incidents/${createdIncident._id}/status`)
      .set('Cookie', engineerCookie)
      .send({
        status: 'investigating',
        reason: 'Investigating Envoy upstream pool configuration',
      });
    assert.equal(resInv.status, 200);
    assert.equal(resInv.body.incident.status, 'investigating');

    // Valid transition 3: investigating -> mitigated
    const resMit = await request(app)
      .patch(`/api/v1/incidents/${createdIncident._id}/status`)
      .set('Cookie', engineerCookie)
      .send({
        status: 'mitigated',
        reason: 'Traffic rerouted to fallback region clusters',
      });
    assert.equal(resMit.status, 200);
    assert.equal(resMit.body.incident.status, 'mitigated');
  });

  test('9. Record verified resolution with root cause, remediation steps, and preventative actions', async () => {
    const resResolve = await request(app)
      .post(`/api/v1/incidents/${createdIncident._id}/resolution`)
      .set('Cookie', engineerCookie)
      .send({
        rootCauseCategory: 'configuration_drift',
        summary: 'Envoy max_requests_per_connection setting dropped to 1 in deployment v3.4.1 causing connection thrashing',
        remediationSteps: [
          'Restored max_requests_per_connection to 1024',
          'Reloaded Envoy config without container restart',
          'Verified 504 error rate dropped to 0.00%',
        ],
        preventativeActions: [
          'Added CI schema lint check for Envoy configuration drift',
          'Configured alerting threshold for connection thrash rate',
        ],
        runbookUrl: 'https://runbooks.resolveiq.io/network/envoy-connection-pool',
      });

    assert.equal(resResolve.status, 200);
    assert.equal(resResolve.body.success, true);
    assert.equal(resResolve.body.incident.status, 'resolved');
    assert.equal(resResolve.body.resolution.rootCauseCategory, 'configuration_drift');
    assert.equal(resResolve.body.resolution.remediationSteps.length, 3);
  });

  test('10. Close incident and then exercise permitted reopening path', async () => {
    // Close incident
    const resClose = await request(app)
      .patch(`/api/v1/incidents/${createdIncident._id}/status`)
      .set('Cookie', commanderCookie)
      .send({
        status: 'closed',
        reason: 'Post-incident review completed and sign-off obtained',
      });
    assert.equal(resClose.status, 200);
    assert.equal(resClose.body.incident.status, 'closed');

    // Reopen attempt without reason fails with 400
    const resReopenNoReason = await request(app)
      .post(`/api/v1/incidents/${createdIncident._id}/reopen`)
      .set('Cookie', engineerCookie)
      .send({});
    assert.equal(resReopenNoReason.status, 400);
    assert.match(resReopenNoReason.body.error, /reason is required/);

    // Reopen incident with mandatory reason
    const resReopen = await request(app)
      .post(`/api/v1/incidents/${createdIncident._id}/reopen`)
      .set('Cookie', engineerCookie)
      .send({
        reason: 'Recurrence observed: 504 errors reappeared on European ingress nodes following secondary deployment',
      });
    assert.equal(resReopen.status, 200);
    assert.equal(resReopen.body.incident.status, 'reopened');
    assert.equal(resReopen.body.incident.reopenedCount, 1);
  });

  test('11. Inspect complete immutable audit history for full workflow lifecycle verification', async () => {
    const resDetail = await request(app)
      .get(`/api/v1/incidents/${createdIncident._id}`)
      .set('Cookie', commanderCookie);

    assert.equal(resDetail.status, 200);
    const auditLogs = resDetail.body.incident.auditLogs;

    // Verify all key lifecycle actions were recorded immutably in order
    const actionsRecorded = auditLogs.map((log) => log.action);
    assert.ok(actionsRecorded.includes('INCIDENT_CREATED'));
    assert.ok(actionsRecorded.includes('INCIDENT_EDITED'));
    assert.ok(actionsRecorded.includes('RESOLVER_ASSIGNED'));
    assert.ok(actionsRecorded.includes('NOTE_ADDED'));
    assert.ok(actionsRecorded.includes('RELATED_TICKET_LINKED'));
    assert.ok(actionsRecorded.includes('STATUS_TRANSITION'));
    assert.ok(actionsRecorded.includes('RESOLUTION_RECORDED'));
    assert.ok(actionsRecorded.includes('INCIDENT_REOPENED'));

    // Verify actors and reasons are preserved
    for (const log of auditLogs) {
      assert.ok(log.actorName);
      assert.ok(log.actorRole);
      assert.ok(log.timestamp);
    }
  });
});
